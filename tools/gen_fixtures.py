"""Generate Phase 1 test fixtures (Solidity) from the Phase 0 netlist builder.

Writes test/fixtures/Fixtures.sol with: the three starter netlists, an 88-gate and an 89-gate random
strategy (exact gate counts, verified against the TAP-02 reference simulator), and their tables.
Run: python3 tools/gen_fixtures.py
"""
import pathlib
import random
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "phase0" / "netlists"))
import gen  # noqa: E402
import tap02_reference as ref  # noqa: E402


def padded_lut(table: int, total: int) -> bytes:
    """Random 6-in function compiled by gen.B (mux tree), padded with dead NAND(0,0) gates so the
    netlist has exactly `total` gates (the 2 output buffers included)."""
    b = gen.B(6)
    ns = [b.nand(2 + i, 2 + i) for i in range(6)]
    level = [(table >> k) & 1 for k in range(64)]
    for var in range(6):
        level = [b.mux(2 + var, level[2 * j], level[2 * j + 1], ns[var]) for j in range(len(level) // 2)]
    out = level[0]
    assert len(b.recs) + 2 <= total, len(b.recs)
    while len(b.recs) + 2 < total:
        b.nand(0, 0)
    data, n = b.finish([out])
    assert n == total
    return data


def table_of(data: bytes) -> int:
    return gen.strategy_table(ref.load(data, 6, 1))


def main():
    rng = random.Random(88)
    out = {}
    for name, fn in [("ALWAYS_DEFECT", gen.build_alld), ("TIT_FOR_TAT", gen.build_tft), ("GRIM_TRIGGER", gen.build_grim)]:
        d, g = fn()
        out[name] = (d, g, table_of(d))
    t = rng.getrandbits(64)
    for n in (88, 89):
        d = padded_lut(t, n)
        tt = table_of(d)
        assert tt == t, "padded LUT must still compute the table"
        out[f"GATES_{n}"] = (d, n, tt)
    lines = ["// SPDX-License-Identifier: Apache-2.0", "// Generated by tools/gen_fixtures.py - do not edit.",
             "pragma solidity ^0.8.24;", "", "library Fixtures {"]
    for k, (d, g, tt) in out.items():
        lines += [f'    bytes internal constant {k} = hex"{d.hex()}";',
                  f"    uint32 internal constant {k}_GATES = {g};",
                  f"    uint64 internal constant {k}_TABLE = 0x{tt:016x};"]
    lines.append("}")
    p = ROOT / "test" / "fixtures" / "Fixtures.sol"
    p.write_text("\n".join(lines) + "\n")
    for k, (d, g, tt) in out.items():
        print(f"{k:14} gates={g:3} bytes={len(d):4} table=0x{tt:016x}")


if __name__ == "__main__":
    main()
